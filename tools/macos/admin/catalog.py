def table_meta(name: str, lang: str) -> tuple[str, str]:
    info = TABLE_INFO.get(name)
    if not info:
        for prefix, meta in PREFIX_INFO:
            if name.startswith(prefix):
                info = meta
                break
    if not info:
        if lang == "zh":
            return name, "未标注的数据表"
        return name, "Unlabeled table"
    zh_t, zh_b, en_t, en_b = info
    return (zh_t, zh_b) if lang == "zh" else (en_t, en_b)
